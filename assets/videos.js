/* ============================================================
   Order validator
   ------------------------------------------------------------
   Runs once on load and stays silent unless something is wrong.
   Catches the three mistakes that are otherwise invisible:

     1. an id in PV_ORDER that matches no video — usually a typo;
        the card silently keeps its old position
     2. the same id listed twice in one category
     3. a video named in a category it is not tagged with, which
        would move a card that the filter then hides anyway

   Open the browser console (F12) after editing the lists above.
   No output means the data is consistent.
   ============================================================ */
(function () {
  if (!window.PV_ORDER || !window.PV_VIDEOS) { return; }

  var byId = {};
  for (var i = 0; i < window.PV_VIDEOS.length; i++) {
    byId[window.PV_VIDEOS[i].id] = window.PV_VIDEOS[i];
  }

  var problems = [];

  for (var key in window.PV_ORDER) {
    if (!Object.prototype.hasOwnProperty.call(window.PV_ORDER, key)) { continue; }

    var list = window.PV_ORDER[key];
    var seen = {};

    for (var j = 0; j < list.length; j++) {
      var id = list[j];
      var video = byId[id];

      if (!video) {
        problems.push("PV_ORDER['" + key + "'] line " + (j + 1) +
                      ": no video has id '" + id + "'");
        continue;
      }

      if (seen[id]) {
        problems.push("PV_ORDER['" + key + "']: '" + id + "' (" +
                      video.title + ") is listed twice");
      }
      seen[id] = true;

      if (key !== 'all' && (video.cat || '').split(' ').indexOf(key) === -1) {
        problems.push("PV_ORDER['" + key + "']: \"" + video.title +
                      "\" is not tagged '" + key + "'");
      }
    }
  }

  if (!problems.length) { return; }

  if (window.console && console.warn) {
    console.warn('PENUELVISION portfolio: ' + problems.length +
                 ' ordering problem(s)');
    for (var p = 0; p < problems.length; p++) {
      console.warn('  ' + problems[p]);
    }
  }
})();
